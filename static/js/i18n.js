function getTranslation(lang, key) {
  return translations[lang]?.[key] || translations.ru[key] || key;
}

function interpolate(text, params = {}) {
  let result = text;
  Object.entries(params).forEach(([key, value]) => {
    result = result.replaceAll(`{${key}}`, value);
  });
  return result;
}

function parseParams(el) {
  const raw = el.getAttribute('data-i18n-params');
  if (!raw) return {};
  try {
    return JSON.parse(raw);
  } catch (_) {
    return {};
  }
}

function translateServerMessage(message, lang) {
  const key = serverMessageKeyMap[message];
  return key ? getTranslation(lang, key) : message;
}

function applyTranslationToElement(el, lang) {
  const key = el.getAttribute('data-i18n');
  if (!key) return;

  const params = parseParams(el);
  const text = interpolate(getTranslation(lang, key), params);
  const prop = el.getAttribute('data-i18n-prop');
  const useHtml = el.getAttribute('data-i18n-html') === 'true';

  if (prop) {
    if (prop in el) {
      el[prop] = text;
    } else {
      el.setAttribute(prop, text);
    }
    return;
  }

  if (el.tagName === 'META') {
    el.setAttribute('content', text);
    return;
  }

  if (useHtml) {
    el.innerHTML = text;
    return;
  }

  el.textContent = text;
}

function applySpecialTranslations(lang) {
  document.querySelectorAll('[data-server-msg]').forEach((el) => {
    const message = el.getAttribute('data-server-msg');
    el.textContent = translateServerMessage(message, lang);
  });

  document.querySelectorAll('[data-level]').forEach((el) => {
    const level = (el.getAttribute('data-level') || '').toLowerCase();
    if (!level) return;
    el.textContent = t(`level.${level}`);
  });
}

function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('lang', lang);

  document.documentElement.setAttribute('lang', lang === 'tj' ? 'tg' : 'ru');
  document.documentElement.setAttribute('data-lang', lang);

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.id === `lang-${lang}`);
  });

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    applyTranslationToElement(el, lang);
  });

  const titleEl = document.querySelector('title[data-i18n-title]');
  if (titleEl) {
    const key = titleEl.getAttribute('data-i18n-title');
    if (!key) {
      applySpecialTranslations(lang);
      return;
    }
    const params = parseParams(titleEl);
    document.title = interpolate(getTranslation(lang, key), params);
  }

  applySpecialTranslations(lang);

  if (typeof window.refreshRichTextToolbars === 'function') {
    window.refreshRichTextToolbars();
  }

  document.dispatchEvent(new CustomEvent('languageChanged', {
    detail: { lang }
  }));
}

function t(key, params = {}) {
  return interpolate(getTranslation(currentLang, key), params);
}

document.addEventListener('DOMContentLoaded', () => {
  setLang(currentLang);
});

